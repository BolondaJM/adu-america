const businessSchema = () => {
  const s = {
    "@context": "https://schema.org",
    "@type": "GeneralContractor",
    name: site.name,
    url: site.url + "/",
    telephone: site.phoneTel.replace("+1", "+1-"),
    email: site.email,
    image: site.url + "/images/hero-backyard.jpg",
    areaServed: markets.map((m) => m.name),
  };
  if (site.address)
    s.address = {
      "@type": "PostalAddress",
      streetAddress: site.address.street,
      addressLocality: site.address.city,
      addressRegion: site.address.state,
      postalCode: site.address.zip,
      addressCountry: "US",
    };
  const sameAs = Object.values(site.socials).filter(Boolean);
  if (sameAs.length) s.sameAs = sameAs;
  if (site.reviews.length) {
    const avg = site.reviews.reduce((a, r) => a + Number(r.rating || 5), 0) / site.reviews.length;
    s.aggregateRating = { "@type": "AggregateRating", ratingValue: avg.toFixed(1), reviewCount: site.reviews.length };
  }
  return s;
};

const planSvg = (m) => {
  const rooms = {
    studio: [["Living and sleeping", 20, 20, 250, 220], ["Kitchen", 270, 20, 110, 110], ["Bath", 270, 130, 110, 110]],
    "1-bedroom": [["Living and kitchen", 20, 20, 220, 220], ["Bedroom", 240, 20, 140, 130], ["Bath", 240, 150, 140, 90]],
    "2-bedroom": [["Living and kitchen", 20, 20, 200, 220], ["Bedroom 1", 220, 20, 160, 95], ["Bath", 220, 115, 160, 50], ["Bedroom 2", 220, 165, 160, 75]],
  }[m.slug] || [["Living and kitchen", 20, 20, 220, 220], ["Bedroom", 240, 20, 140, 130], ["Bath", 240, 150, 140, 90]];
  const r = rooms
    .map(([n, x, y, w, h]) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" /><text x="${x + w / 2}" y="${y + h / 2}" text-anchor="middle" dominant-baseline="middle">${n}</text>`)
    .join("");
  return `<svg class="plan" viewBox="0 0 400 260" role="img" aria-label="Schematic floor plan of the ${esc(m.name)} model">${r}</svg>`;
};

