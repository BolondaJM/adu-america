function breadcrumbs(crumbs) {
  if (!crumbs || !crumbs.length) return "";
  const all = [["Home", "/"], ...crumbs];
  const items = all
    .map(([l, h], i) =>
      i === all.length - 1 ? `<li aria-current="page">${esc(l)}</li>` : `<li><a href="${h}">${esc(l)}</a></li>`
    )
    .join("");
  return `<nav class="crumbs" aria-label="Breadcrumb"><ol>${items}</ol></nav>`;
}

function crumbSchema(crumbs) {
  if (!crumbs || !crumbs.length) return null;
  const all = [["Home", "/"], ...crumbs];
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: all.map(([name, href], i) => ({
      "@type": "ListItem",
      position: i + 1,
      name,
      item: site.url + href,
    })),
  };
}

function layout({ path, title, desc, body, crumbs, schema = [], noindex = false, variant, image = "/images/hero-backyard.jpg", file }) {
  const full = title.includes(site.name) ? title : `${title} | ${site.name}`;
  const url = site.url + path;
  const schemas = [crumbSchema(crumbs), ...schema].filter(Boolean);
  const html = `<!DOCTYPE html>
${GEN}
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(full)}</title>
    <meta name="description" content="${esc(desc)}" />
    <meta name="theme-color" content="#132339" />
    ${noindex ? '<meta name="robots" content="noindex, nofollow" />' : ""}
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="canonical" href="${url}" />
    <meta property="og:title" content="${esc(full)}" />
    <meta property="og:description" content="${esc(desc)}" />
    <meta property="og:type" content="website" />
    <meta property="og:url" content="${url}" />
    <meta property="og:image" content="${site.url}${image}" />
    <meta property="og:image:width" content="1280" />
    <meta property="og:image:height" content="720" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:image" content="${site.url}${image}" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Hind+Vadodara:wght@400;500;700&family=Montserrat:ital,wght@0,600;1,500&family=Taviraj:wght@400;500&display=swap" rel="stylesheet" />
    <!--@head-->
    ${schemas.map((s) => `<script type="application/ld+json">${JSON.stringify(s)}</script>`).join("\n    ")}
  </head>
  <body${variant === "minimal" ? ' data-minimal="true"' : ' data-solid="true"'}>
    <a class="skip" href="#main">Skip to content</a>
    <div class="progress" id="progress" aria-hidden="true"></div>
    <!--@header${variant === "minimal" ? ":minimal" : ""}-->
    <main id="main">
${body}
    </main>
    <!--@footer${variant === "minimal" ? ":minimal" : ""}-->
    <script type="module" src="/main.js"></script>
  </body>
</html>
`;
  const out = file || `${path.replace(/^\//, "")}index.html`;
  write(out, html);
  pages.push({ path, title: title.replace(` | ${site.name}`, ""), desc, noindex });
}

